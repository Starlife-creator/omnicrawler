class IconRegistry:
    """Theme-aware SVG icon cache.

    All method calls are static; the registry holds no per-instance state.
    """

    _color_map: dict[str, str] = {
        "primary": "primary",
        "muted": "muted",
        "text": "text",
        "danger": "danger",
        "success": "success",
    }

    @staticmethod
    def icon(name: str, *, size: int = 24, color: str = "primary") -> QIcon:
        """Return a :class:`QIcon` from the named SVG, colored for the current theme.

        Args:
            name: Icon key (e.g. ``"save"``, ``"run"``).
            size: Pixel dimensions (square).
            color: Token key — ``"primary"``, ``"muted"``, ``"text"``,
                   ``"danger"``, ``"success"``.

        Returns:
            A theme-colored QIcon. Returns an empty icon if *name* is unknown.

        Icons are cached by ``(name, size, color)``, so repeated
        lookups of the same params avoid re-rendering.
        """
        svg = _SVG_ICONS.get(name)
        if svg is None:
            return QIcon()
        qcolor = IconRegistry._resolve_color(color)
        cache_key = (name, size, qcolor.name())
        return _build_icon_cached(svg, size, qcolor.name(), cache_key)

    @staticmethod
    def _resolve_color(key: str) -> QColor:
        """Map a semantic color key to the current VisualTokens value."""
        try:
            from .design_system import ThemeManager
            tokens = ThemeManager.instance().tokens
        except Exception:
            return QColor("#176B87")

        color_map = {
            "primary": tokens.primary,
            "muted": tokens.muted,
            "text": tokens.text,
            "danger": tokens.danger,
            "success": tokens.success,
        }
        return QColor(color_map.get(key, tokens.primary))

    @staticmethod
    def names() -> list[str]:
        """Return all registered icon names."""
        return sorted(_SVG_ICONS.keys())


@lru_cache(maxsize=200)
def _build_icon_cached(svg: str, size: int, fill_color: str, _cache_key: tuple) -> QIcon:
    """Render SVG to QIcon with the given fill color.  Cached via lru_cache."""
    colored = svg.replace('stroke="currentColor"', f'stroke="{fill_color}"')
    colored = colored.replace('fill="none"', 'fill="none"')

    renderer = QSvgRenderer(QByteArray(colored.encode("utf-8")))
    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()
    return QIcon(pixmap)
